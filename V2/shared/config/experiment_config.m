function cfg = experiment_config()
% EXPERIMENT_CONFIG  Single shared configuration for UAV swarm benchmarks.
%
% All generators, algorithm runners, and plotting scripts read parameters
% from this file instead of hard-coding them.

thisFile  = mfilename('fullpath');
configDir = fileparts(thisFile);
sharedDir = fileparts(configDir);
rootDir   = fileparts(sharedDir);

cfg = struct();

% ---- Canonical Directory Paths ----
cfg.paths = struct( ...
    'rootDir',       rootDir, ...
    'sharedDir',     sharedDir, ...
    'configDir',     configDir, ...
    'datasetsDir',   fullfile(sharedDir, 'datasets'), ...
    'generatorsDir', fullfile(sharedDir, 'generators'), ...
    'plottingDir',   fullfile(sharedDir, 'plotting'), ...
    'resultsRoot',   fullfile(rootDir, 'results'), ...
    'plotsRoot',     fullfile(rootDir, 'plots'));

% ---- Scenario Definitions ----
cfg.scenarios.names = {'small', 'large'};
cfg.scenarios.small = struct( ...
    'name',            'small', ...
    'label',           'Small', ...
    'nUAV',            5, ...
    'nPayloads',       2, ...
    'capabilities',    {{'Camera', 'Thermal'}}, ...
    'totalSlots',      8, ...
    'uavSlotsPerUAV',  [2, 1, 1, 2, 2], ...
    'nTasks',          80, ...
    'worldBox',        [100, 100, 25], ...
    'worldDiag',       100 * sqrt(3), ...
    'nominalCapacity', 16, ...
    'qSlotEstDivisor', 5, ...
    'speed',           5, ...
    'execTimeRange',   [16, 24], ...
    'tEnd',            450, ...
    'dt',              1);

cfg.scenarios.large = struct( ...
    'name',            'large', ...
    'label',           'Large', ...
    'nUAV',            10, ...
    'nPayloads',       3, ...
    'capabilities',    {{'Camera', 'Thermal', 'LiDAR'}}, ...
    'totalSlots',      19, ...
    'uavSlotsPerUAV',  [2, 2, 2, 3, 1, 1, 1, 2, 2, 3], ...
    'nTasks',          120, ...
    'worldBox',        [150, 150, 35], ...
    'worldDiag',       150 * sqrt(3), ...
    'nominalCapacity', 12, ...
    'qSlotEstDivisor', 10, ...
    'speed',           5, ...
    'execTimeRange',   [16, 24], ...
    'tEnd',            450, ...
    'dt',              1);

% ---- Algorithm Hyperparameters ----
cfg.bdtr = struct('gamma', 0.5, 'delta', 0.9, 'alpha', 0.5);

% ---- Attack Strategies (label kept separate from code string) ----
cfg.strategies = struct( ...
    'label', {'Random', 'Balanced', 'Direct'}, ...
    'code',  {'random', 'balanced', 'directed'});

% ---- Experiment 1: Attack Robustness (3 strategies x 3 strengths x 30 seeds) ----
cfg.attack = struct( ...
    'experimentName', 'attack', ...
    'strengths',      [0.40, 0.55, 0.70], ... % fractions only: 0 < strength < 1
    'realisedSlots',  struct('small', [3, 4, 6], 'large', [8, 10, 13]), ...
    'timingWindow',   [0.15, 0.60], ...
    'nReps',          30, ...
    'seeds',          1:30);

% ---- Experiment 2: Monte Carlo Stability (fixed strategy & strength, 300 seeds) ----
cfg.montecarlo = struct( ...
    'experimentName', 'montecarlo', ...
    'strategyLabel',  'Random', ...
    'strategyCode',   'random', ...
    'strength',       0.55, ...
    'realisedSlots',  struct('small', 4, 'large', 10), ...
    'timingWindow',   [0.15, 0.60], ...
    'nRuns',          300, ...
    'seeds',          1001:1300);

% ---- Seed Rules (disjoint instance and attack streams) ----
cfg.seeding = struct( ...
    'masterSeed',         20261128, ...
    'rngAlgorithm',       'twister', ...
    'instanceSeedOffset', 0, ...
    'attackSeedOffset',   100000, ...
    'instanceSeedRule',   'seed', ...
    'attackSeedRule',     'seed + 100000');

% ---- Metrics & Outcomes ----
cfg.metrics = struct( ...
    'recorded',  {{'feasibilityRate', 'completionRate', 'failedRate', 'unfinishedRate', ...
                   'reallocationCount', 'preemptionCount', 'meanCompletionTime', ...
                   'R_task', 'R_time', 'CRI', 'throughputRecovery'}}, ...
    'outcomes',  {{'completionRate', 'failedRate', 'unfinishedRate'}}, ...
    'labels',    struct( ...
        'completionRate', 'completed', ...
        'failedRate',     'failed by deadline', ...
        'unfinishedRate', 'unfinished at horizon (tEnd)'), ...
    'primary',   'completionRate', ...
    'secondary', 'failedRate');

% ---- Plotting Specification ----
cfg.plotting = struct( ...
    'colormap', 'parula', ...
    'dpi',      300, ...
    'format',   'png', ...
    'mcSummary', struct( ...
        'metrics', {{'CRI', 'R_time', 'R_task'}}, ...
        'zValue',  1.95996, ...
        'yLim',    [0.4, 0.8]));
end
